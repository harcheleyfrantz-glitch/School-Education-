#!/usr/bin/env python3
"""Installs converted real-airport layouts into the game.

  - copies OUT_DIR/ICAO.json to data/real_airports/
  - rewrites each airport's "runways" block in src/data/airports.gd with the real runways
    (same order as the layout file, which the taxi network's runway indices refer to)
  - writes src/data/real_airports.gd (the list and the fence outline of every real airport)

Usage: python3 apply.py OUT_DIR ICAO[,ICAO...]   (run from the project root)
"""
import json, math, os, re, shutil, sys

OUT, APS = sys.argv[1], sys.argv[2].split(",")
os.makedirs("data/real_airports", exist_ok=True)
src = open("src/data/airports.gd", encoding="utf-8").read()
outlines = {}
for icao in APS:
    d = json.load(open(os.path.join(OUT, icao + ".json")))
    shutil.copy(os.path.join(OUT, icao + ".json"), "data/real_airports/%s.json" % icao)
    lines = []
    for r in d["runways"]:
        ax, az = r["a"]
        bx, bz = r["b"]
        dx, dz = bx - ax, bz - az
        ln = math.hypot(dx, dz)
        h = math.degrees(math.atan2(dx, -dz)) % 360.0
        hr = math.radians(h)
        dirv = (math.sin(hr), -math.cos(hr))
        right = (math.cos(hr), math.sin(hr))
        cx, cz = (ax + bx) * 0.5, (az + bz) * 0.5
        off = cx * right[0] + cz * right[1]
        along = cx * dirv[0] + cz * dirv[1]
        lines.append('\t\t\t{"id": "%s", "hdg": %.2f, "len": %.1f, "wid": %.1f, "off": %.1f, "along": %.1f, "ils": [true, true], "surface": "asphalt"},'
            % (r["id"], h, ln, r["wid"], off, along))
    block = '"runways": [\n' + "\n".join(lines) + "\n\t\t],"
    # the airport's entry, then its runways array
    m = re.search(r'\n\t"%s": \{' % icao, src)
    if not m:
        print("no entry for", icao)
        continue
    start = m.end()
    rm = re.compile(r'"runways": \[\n.*?\n\t\t\],', re.S).search(src, start)
    if not rm:
        print("no runways for", icao)
        continue
    src = src[:rm.start()] + block + src[rm.end():]
    outlines[icao] = [round(v, 1) for p in d["outline"] for v in p]
    print(icao, len(d["runways"]), "runways,", len(d["stands"]), "stands")
open("src/data/airports.gd", "w", encoding="utf-8").write(src)

ol = ",\n".join('\t"%s": [%s]' % (k, ", ".join("%.1f" % v for v in vals)) for k, vals in outlines.items())
open("src/data/real_airports.gd", "w", encoding="utf-8").write('''class_name RealAirports
## One-to-one layouts of real airports, generated by tools/real_airports from open data:
## runways from OurAirports (public domain); taxiways with their names, gates, aprons and building
## footprints from OpenStreetMap via Overture Maps (ODbL, (c) OpenStreetMap contributors); pavement
## outlines and tower positions from the FlightGear / X-Plane airport database (GPL).
## Big arrays in the JSON files are base64 little-endian float32 / int32.

const DIR := "res://data/real_airports/"
## Fence outline of each real airport (airport-local metres, x, z pairs; convex hull of the
## pavement, runways and terminals), so the world can fence the airport without loading it.
const OUTLINE := {
%s,
}

static var _cache := {}
static var _mutex := Mutex.new()


static func has(icao: String) -> bool:
	return OUTLINE.has(icao)


static func outline(icao: String) -> PackedVector2Array:
	var out := PackedVector2Array()
	var a: Array = OUTLINE.get(icao, [])
	for i in range(0, a.size() - 1, 2):
		out.append(Vector2(float(a[i]), float(a[i + 1])))
	return out


static func get_data(icao: String) -> Dictionary:
	## The decoded layout file (cached; safe to call from the airport builder threads).
	_mutex.lock()
	if not _cache.has(icao):
		_cache[icao] = _load(icao)
	var d: Dictionary = _cache[icao]
	_mutex.unlock()
	return d


static func _load(icao: String) -> Dictionary:
	var path := DIR + icao + ".json"
	if not FileAccess.file_exists(path):
		return {}
	var parsed = JSON.parse_string(FileAccess.get_file_as_string(path))
	if typeof(parsed) != TYPE_DICTIONARY:
		return {}
	var d: Dictionary = parsed
	d.nodes_f = _f32(d.nodes)
	d.kinds_i = _i32(d.kinds)
	d.nrw_i = _i32(d.nrw)
	d.edges_i = _i32(d.edges)
	d.pa_vf = _f32(d.pa_v)
	d.pa_ii = _i32(d.pa_i)
	d.pt_vf = _f32(d.pt_v)
	d.pt_ii = _i32(d.pt_i)
	for b in d.buildings:
		b.poly = _ring(b.p)
		var hs := []
		for h in b.holes:
			hs.append(_ring(h))
		b.hole_rings = hs
		b.roof = _i32(b.ri)
	return d


static func _f32(s: String) -> PackedFloat32Array:
	return Marshalls.base64_to_raw(s).to_float32_array()


static func _i32(s: String) -> PackedInt32Array:
	return Marshalls.base64_to_raw(s).to_int32_array()


static func _ring(s: String) -> PackedVector2Array:
	var f := _f32(s)
	var out := PackedVector2Array()
	out.resize(f.size() / 2)
	for i in out.size():
		out[i] = Vector2(f[i * 2], f[i * 2 + 1])
	return out
''' % ol)
print("wrote src/data/real_airports.gd with", len(outlines), "airports")
