package com.rodwave.engine.compat

import com.rodwave.engine.RodwaveEngine

/** Plain-text/Markdown troubleshooting report that users can share. */
object CompatibilityReport {
    fun render(
        statuses: List<ComponentStatus>,
        scan: ScanResult?,
        game: InstalledGame?,
        deviceInfo: Map<String, String> = emptyMap(),
        generatedAt: String? = null,
    ): String = buildString {
        appendLine("# Rodwave compatibility report")
        appendLine()
        appendLine("Generated by ${RodwaveEngine.NAME} ${RodwaveEngine.VERSION}${generatedAt?.let { " on $it" } ?: ""}.")
        appendLine("States are based only on the evidence listed; file names alone never count as verification.")
        appendLine()
        if (deviceInfo.isNotEmpty()) {
            appendLine("## Device")
            deviceInfo.forEach { (k, v) -> appendLine("- $k: $v") }
            appendLine()
        }
        appendLine("## Game package")
        if (game == null) {
            appendLine("- Not installed or not visible to Rodwave")
        } else {
            appendLine("- Package: ${game.packageName}")
            appendLine("- Version: ${game.versionName ?: "?"} (code ${game.versionCode ?: "?"})")
            appendLine("- ABIs: ${game.abis.joinToString { it.androidName }.ifEmpty { "unknown" }}")
            appendLine("- APK readable: ${if (game.apkReadable) "yes" else "no"}")
            if (game.nativeLibraries.isNotEmpty()) appendLine("- Native libraries in APK: ${game.nativeLibraries.sorted().joinToString()}")
        }
        appendLine()
        appendLine("## Scanned folder")
        if (scan == null) {
            appendLine("- No folder scanned")
        } else {
            appendLine("- Folder: ${scan.rootName} — ${scan.location.label} (confidence: ${scan.locationConfidence.label})")
            appendLine("- Files scanned: ${scan.filesScanned}${if (scan.truncated) " (limit reached)" else ""}")
            appendLine("- Scripts: ${scan.scripts.size}, native libraries: ${scan.nativeMods.size}, configs: ${scan.configFiles.size}, saves: ${scan.saveFiles.size}")
            scan.amlCore?.let { appendLine("- AML core config: version ${it.version ?: "?"}, last launch ${it.lastLaunchEpochSeconds ?: "?"} (epoch s)") }
            scan.errors.take(20).forEach { appendLine("- Read error: $it") }
        }
        appendLine()
        appendLine("## Components")
        for (s in statuses) {
            appendLine()
            appendLine("### ${s.profile.name} — ${s.state.label}")
            appendLine(s.summary)
            s.evidence.forEach { e -> appendLine("- [${e.confidence.label}] ${e.text}${e.path?.let { p -> " ($p)" } ?: ""}") }
        }
        if (scan != null && scan.scripts.isNotEmpty()) {
            appendLine()
            appendLine("## Scripts")
            for (script in scan.scripts) {
                val r = script.report
                appendLine("- ${script.path}: ${r?.verdict?.label ?: "not analysed"}${r?.scriptName?.let { " (name '$it')" } ?: ""}")
                r?.findings?.forEach { f -> appendLine("  - ${f.severity.name.lowercase()}: ${f.title} — ${f.detail}") }
            }
        }
    }
}
